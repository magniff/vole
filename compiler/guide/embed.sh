#!/bin/sh
# Makes compiler/src/guide/text/ from the guide's source (0.13): for each
# topic of compiler/guide/topics.txt (`name: summary`, in the order
# `volec guide --list` prints them), t_NAME.vl holds a function that
# writes compiler/guide/NAME.md to a buffer, one call per line (string
# literals cannot span lines; 0.25.3: a topic of more than 990 lines in
# functions of 990 calls, part0, part1, ..., that text calls in turn);
# mod.vl has the table of topics. Run it after changing the guide;
# tests/guide/run.sh checks they agree.
#
# usage: compiler/guide/embed.sh [-c]   (-c: only check, exit 1 if stale)
set -eu
LC_ALL=C
export LC_ALL
cd "$(dirname "$0")/../.."
src=compiler/guide
out=compiler/src/guide/text
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# A [u8] literal's text: backslashes and quotes escaped.
escape() {
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

names=""
count=0
chunk=990
while IFS= read -r line; do
    case "$line" in ''|'#'*) continue ;; esac
    name=${line%%:*}
    [ -f "$src/$name.md" ] || { echo "embed.sh: no $src/$name.md for topic '$name'" >&2; exit 1; }
    mod=t_$(printf '%s' "$name" | tr '-' '_')
    escape <"$src/$name.md" | sed -e 's/^/    buf_bytes(out, "/' -e 's/$/\\n");/' >"$tmp/body"
    lines=$(wc -l <"$tmp/body" | tr -d ' ')
    {
        echo "// Generated by compiler/guide/embed.sh from compiler/guide/$name.md (do"
        echo "// not edit): the guide's topic '$name'."
        echo ""
        echo "use crate::base::buf_bytes;"
        echo ""
        echo "pub fn text(out: i64) {"
        if [ "$lines" -le "$chunk" ]; then
            cat "$tmp/body"
            echo "}"
        else
            # (0.25.3) a long topic: functions of $chunk lines each
            k=0
            while [ $((k * chunk)) -lt "$lines" ]; do
                echo "    part$k(out);"
                k=$((k + 1))
            done
            echo "}"
            k=0
            while [ $((k * chunk)) -lt "$lines" ]; do
                echo ""
                echo "fn part$k(out: i64) {"
                sed -n "$((k * chunk + 1)),$(((k + 1) * chunk))p" "$tmp/body"
                echo "}"
                k=$((k + 1))
            done
        fi
    } >"$tmp/$mod.vl"
    rm -f "$tmp/body"
    [ "$lines" -le 4000 ] || { echo "embed.sh: $src/$name.md has $lines lines (over 4000): split the topic" >&2; exit 1; }
    names="$names $name"
    count=$((count + 1))
done <"$src/topics.txt"

{
    echo "// Generated by compiler/guide/embed.sh from compiler/guide/ (do not edit):"
    echo "// the guide's topics, in the order of topics.txt."
    echo ""
    for name in $names; do
        echo "pub mod t_$(printf '%s' "$name" | tr '-' '_');"
    done
    echo ""
    echo "pub const TOPIC_COUNT: i64 = $count;"
    echo ""
    echo "pub fn topic_name(i: i64) -> [u8] {"
    echo "    match i {"
    i=0
    for name in $names; do
        echo "        $i => \"$name\","
        i=$((i + 1))
    done
    echo "        _ => \"\","
    echo "    }"
    echo "}"
    echo ""
    echo "pub fn topic_summary(i: i64) -> [u8] {"
    echo "    match i {"
    i=0
    while IFS= read -r line; do
        case "$line" in ''|'#'*) continue ;; esac
        summary=$(printf '%s\n' "${line#*: }" | escape)
        echo "        $i => \"$summary\","
        i=$((i + 1))
    done <"$src/topics.txt"
    echo "        _ => \"\","
    echo "    }"
    echo "}"
    echo ""
    echo "// Writes topic i's text to buffer out."
    echo "pub fn topic_text(i: i64, out: i64) {"
    echo "    match i {"
    i=0
    for name in $names; do
        echo "        $i => t_$(printf '%s' "$name" | tr '-' '_')::text(out),"
        i=$((i + 1))
    done
    echo "        _ => {}"
    echo "    }"
    echo "}"
} >"$tmp/mod.vl"

if [ "${1:-}" = "-c" ]; then
    if diff -r "$tmp" "$out" >/dev/null 2>&1; then exit 0; fi
    echo "$out is stale: run compiler/guide/embed.sh" >&2
    exit 1
fi
rm -rf "$out"
mkdir -p "$out"
cp "$tmp"/*.vl "$out/"
