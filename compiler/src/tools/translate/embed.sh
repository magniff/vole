#!/bin/sh
# Makes compiler/src/tools/translate/table.vl (0.27.3), the translator's
# tables, from std2's files: rewrite.tsv's rows (the std part of `fix
# --edition rust`'s table), the paths of std2's items that MVS's std had
# (checklist.tsv's `mvs` column: an MVS name, the std2 item it is now) and
# the names of std2's prelude (prelude.vl); and (0.28.0) statics.tsv's
# rows, beside this script (the accessors of compiler/src's statics,
# tools/translate/statics.vl). Each is a function that writes
# its rows to a buffer, one call per line (a string literal does not span
# lines). Run it after changing those files; tests/run's case
# fix_edition_table and tools/premerge.sh check that they agree.
#
# usage: compiler/src/tools/translate/embed.sh [-c]   (-c: only check)
set -eu
LC_ALL=C
export LC_ALL
cd "$(dirname "$0")/../../../.."
std2=compiler/std2
out=compiler/src/tools/translate/table.vl
check=0
[ "${1:-}" = "-c" ] && check=1
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# A [u8] literal's text: backslashes, quotes and tabs escaped; (0.28.0)
# `b"..."` when compiler/src is in the rust edition (its root's
# `// EDITION: rust`), as `fix --edition rust` writes it.
q='"'
grep -q '^// EDITION: rust *$' compiler/src/main.vl && q='b"'
lit() {
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/	/\\t/g' \
        -e "s/^/    buf_bytes(out, $q/" -e 's/$/\\n");/'
}

{
    echo "// Generated by compiler/src/tools/translate/embed.sh from compiler/std2's"
    echo "// rewrite.tsv, checklist.tsv and prelude.vl, and statics.tsv (do not edit): the"
    echo "// translator's tables (tools/translate/table rows)."
    echo ""
    echo "use crate::base::buf_bytes;"
    echo ""
    echo "// rewrite.tsv's rows: mvs, when, rust, note."
    echo "pub fn rewrite_rows(out: i64) {"
    grep -v '^#' "$std2/rewrite.tsv" | sed 1d | grep . | lit
    echo "}"
    echo ""
    echo "// An MVS std item's name, the std2 item it is (its path)."
    echo "pub fn path_rows(out: i64) {"
    awk -F'\t' '
        /^#/ || $1 == "module" { next }
        $2 !~ /::/ && $2 ~ /^[A-Za-z_]/ && $5 != "" {
            n = split($5, m, ",")
            for (i = 1; i <= n; i++) {
                if (m[i] !~ /::/ && m[i] !~ / /) {
                    print m[i] "\t" $1 "::" $2
                }
            }
        }
        # (0.27.3) then every capitalized item std2 has, as itself: a name
        # a row writes (`Layout`, `NonNull`), which MVS had in its prelude
        $2 !~ /::/ && $2 ~ /^[A-Z]/ && ($3 == "struct" || $3 == "enum" || $3 == "trait") \
            && $1 !~ /__/ {
            later[n_later++] = $2 "\t" $1 "::" $2
        }
        END { for (i = 0; i < n_later; i++) print later[i] }' "$std2/checklist.tsv" | lit
    echo "}"
    echo ""
    echo "// The names std2's prelude holds."
    echo "pub fn prelude_rows(out: i64) {"
    sed -n '/^pub use/,$p' "$std2/prelude.vl" | tr '\n' ' ' | sed 's/;/;\
/g' | sed -n 's/^ *pub use crate::\(.*\);/\1/p' | sed 's/.*::{\(.*\)}/\1/; s/.*:://' \
        | tr ',' '\n' | sed 's/ //g' | grep . | sort -u | lit
    echo "}"
    echo ""
    echo "// (0.28.0) statics.tsv's rows: name, verdict, unsafe, safety."
    echo "pub fn static_rows(out: i64) {"
    grep -v '^#' compiler/src/tools/translate/statics.tsv | grep . | cut -f1-4 | lit
    echo "}"
} >"$tmp/table.vl"

if [ "$check" = 1 ]; then
    if ! cmp -s "$tmp/table.vl" "$out"; then
        echo "translate/embed.sh: $out is stale: run compiler/src/tools/translate/embed.sh" >&2
        exit 1
    fi
    exit 0
fi
cp "$tmp/table.vl" "$out"
echo "translate/embed.sh: wrote $out"
